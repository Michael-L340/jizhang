-- 里外页面：外页面显示的账户余额 = 真实余额 + 偏移量。
--
-- 存的是「偏移量」而不是「一个写死的对外余额」：偏移量固定，两边就同幅波动——
-- 在外页面记一笔，外面那个数跟着动，看起来是活的；写死一个数则一个月后还是原样，一眼假。
--
-- 单位是整数「分」，不是 numeric(12,2) 的元。accounts 表本来就没有别的金额列，
-- 不存在和谁不一致的问题；存分省掉一层元↔分转换，也就少一处会算错 100 倍的地方
-- ——备份脚本历史上正是在元/分这件事上栽过。
--
-- null = 这个账户不做修饰，里外一样。白条账户不参与（代码里也挡了一道）。
alter table public.accounts
  add column if not exists facade_offset integer;
