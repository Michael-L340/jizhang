-- 京东白条的规矩：这个还款周期里**已经还过款**之后再下的单，平台会算进下一期。
--
-- 用户 2026-09-09 实测：9/9 还清了 9/17 那期的账单，当天再打白条，京东那边算的是 10/17，
-- 而 App 只会算「下单日之后最近的还款日」= 9/17，于是面板追着要一笔平台根本没要的钱。
-- （面板上那行「本期已还过款，这笔可能算下期」的提示就是为这个留的，现在真改了。）
--
-- 为什么是账户上的开关而不是全局规则：用户明确说**只有京东这样**，花呗 / 美团 / 拼多多不这样。
-- 也不能按账户名判「包含京东」——改个名字行为就会静默变掉。
--
-- null / false = 不启用，退回原来的「下单日之后最近的还款日」。老数据和没设的账户一点不受影响。
--
-- App 判「有没有还过款」只看你自己记的那笔转账（银行 → 白条），它读不到平台账单。
-- 在平台还了钱却没记进来，这条规则就不会生效——这是它的边界。
alter table public.accounts
  add column if not exists defer_after_repay boolean;
